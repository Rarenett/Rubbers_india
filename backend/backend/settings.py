# ==============================================================================
# Python 3.13 / Django SMTP Compatibility Patch
# ==============================================================================
# DO NOT REMOVE THIS PATCH!
# In Python 3.13, smtplib.SMTP.starttls() removed the 'keyfile' and 'certfile' 
# arguments. Older versions of Django still attempt to pass them, causing 
# email sending to crash globally. This patch intercepts the call and fixes it.
import smtplib
import ssl

original_starttls = smtplib.SMTP.starttls

def smtplib_patch(self, keyfile=None, certfile=None, context=None):
    if context is None:
        context = ssl.create_default_context()
        if keyfile and certfile:
            context.load_cert_chain(certfile=certfile, keyfile=keyfile)
    return original_starttls(self, context=context)

smtplib.SMTP.starttls = smtplib_patch
