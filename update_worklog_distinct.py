import os
import re
from datetime import datetime

worklog_path = r"c:\Paul@Rarenett\glenda_vite1\WORKLOG.md"

with open(worklog_path, 'r', encoding='utf-8') as f:
    content = f.read()

today_str = datetime.now().strftime("%Y-%m-%d")
time_str = datetime.now().strftime("%H:%M IST")

entry = f"""
## {today_str}

### 🐛 Fix: Duplicate entries for employees in Marketing Attendance Report
**Files:** `backend/project_app/views.py`

- Fixed a bug where `Aleena` (or other users) appeared multiple times in the daily report.
- The duplication was caused by the Django OR (`|`) `Q` object query on related fields `Employee.objects.filter(...)`.
- Appended `.distinct()` to the queryset in `daily_report` to ensure each employee is fetched exactly once.
"""

if "## " + today_str in content:
    pass

last_updated_regex = r"\*Last updated:.*?\*"

if re.search(last_updated_regex, content):
    content = re.sub(last_updated_regex, "", content).rstrip()

content += "\n\n---\n" + entry + f"\n\n*Last updated: {today_str} {time_str}*\n"

with open(worklog_path, 'w', encoding='utf-8') as f:
    f.write(content)

print("WORKLOG updated successfully.")
